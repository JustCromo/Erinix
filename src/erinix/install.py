"""Install Erinix like a normal desktop app (no root, nothing outside your home).

- a launcher `~/.local/bin/erinix` that runs Erinix from its own Python environment,
  so you never activate a venv again;
- an application-menu entry (`erinix.desktop`) with the Erinix icon;
- the icon in SVG and PNG, generated from the mascot.

Safety: files are written only under the given home folder, symlinks at the target are
refused, a launcher that was not made by Erinix is never overwritten without --force,
and paths with unusual characters are rejected (they would break the desktop entry).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Mapping

from erinix import assets

MARKER = "# Generated by `erinix install-app`"
SAFE_CHARS = frozenset("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_./+@:=,-")

# name -> arguments placed between the terminal and the command
TERMINALS: dict[str, tuple[str, ...]] = {
    "kitty": ("--class", "erinix", "--title", "Erinix"),
    "foot": ("--app-id", "erinix"),
    "alacritty": ("--class", "erinix", "--title", "Erinix", "-e"),
    "wezterm": ("start", "--class", "erinix", "--"),
    "ghostty": ("--class=erinix", "-e"),
    "gnome-terminal": ("--",),
    "konsole": ("-e",),
    "xterm": ("-class", "erinix", "-e"),
}


class InstallError(Exception):
    """Something prevents a safe installation."""


@dataclass
class InstallResult:
    written: list[Path] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    terminal: str | None = None


def _check_safe(value: str, what: str) -> str:
    if not value or any(c not in SAFE_CHARS for c in value):
        raise InstallError(f"{what} contains characters that are not safe in a desktop entry: {value!r}")
    return value


def pick_terminal(preferred: str | None, env: Mapping[str, str], which: Callable[[str], str | None]) -> str | None:
    candidates = [preferred] if preferred else [Path(env.get("TERMINAL", "")).name, *TERMINALS]
    for name in candidates:
        if name and name in TERMINALS and which(name):
            return name
    return None


def _write(path: Path, data: bytes, mode: int, *, force: bool = False, marker: bool = False) -> None:
    if os.path.islink(path):
        raise InstallError(f"{path} is a symlink: refusing to write through it")
    if marker and path.exists() and not force:
        existing = path.read_bytes()[:4096]
        if MARKER.encode() not in existing:
            raise InstallError(f"{path} already exists and was not made by Erinix (use --force to replace it)")
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".erinix-")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def launcher_script(python: str) -> bytes:
    _check_safe(python, "the Python path")
    return (f"#!/bin/sh\n{MARKER}\n"
            "# Runs Erinix from its own Python environment: no need to activate a venv.\n"
            f'exec "{python}" -m erinix.cli "$@"\n').encode()


def desktop_entry(launcher: str, terminal: str | None) -> bytes:
    _check_safe(launcher, "the launcher path")
    if terminal:
        exec_line = " ".join((terminal, *TERMINALS[terminal], launcher))
        terminal_flag = "false"
    else:
        exec_line, terminal_flag = launcher, "true"
    return (f"[Desktop Entry]\n{MARKER}\nType=Application\nVersion=1.1\nName=Erinix\nGenericName=Intrusion detection\n"
            "Comment=Host intrusion detection (Nemirix suite)\n"
            f"Exec={exec_line}\nIcon=erinix\nTerminal={terminal_flag}\nCategories=System;Security;Monitor;\n"
            "Keywords=security;ids;intrusion;monitor;logs;\nStartupWMClass=erinix\nActions=Dashboard;\n\n"
            f"[Desktop Action Dashboard]\nName=Open the dashboard\nExec={launcher} ui\n").encode()


def install_app(home: Path, *, python: str, terminal: str | None = None, force: bool = False,
                env: Mapping[str, str] | None = None, which: Callable[[str], str | None] = shutil.which,
                run: Callable[..., object] = subprocess.run) -> InstallResult:
    env = os.environ if env is None else env
    home = Path(home)
    if terminal is not None and terminal not in TERMINALS:
        raise InstallError(f"unknown terminal {terminal!r} (known: {', '.join(TERMINALS)})")
    chosen = pick_terminal(terminal, env, which)
    if terminal and not chosen:
        raise InstallError(f"{terminal} is not installed")
    launcher = home / ".local" / "bin" / "erinix"
    apps = home / ".local" / "share" / "applications"
    icons = home / ".local" / "share" / "icons" / "hicolor"
    result = InstallResult(terminal=chosen)
    plan = [
        (launcher, launcher_script(python), 0o755, True),
        (apps / "erinix.desktop", desktop_entry(str(launcher), chosen), 0o644, True),
        (icons / "scalable" / "apps" / "erinix.svg", assets.logo_svg().encode(), 0o644, False),
        (icons / "256x256" / "apps" / "erinix.png", assets.logo_png(256), 0o644, False),
    ]
    for path, data, mode, marker in plan:
        _write(path, data, mode, force=force, marker=marker)
        result.written.append(path)
    for command in ((["update-desktop-database", "-q", str(apps)]), (["gtk-update-icon-cache", "-q", "-t", str(icons)])):
        if which(command[0]):
            try:
                run(command, check=False, timeout=15, capture_output=True)
            except (OSError, subprocess.SubprocessError):
                pass
    if not chosen:
        result.notes.append("No known terminal was found: the menu entry will ask your desktop to open one.")
    path_dirs = [p for p in env.get("PATH", "").split(os.pathsep) if p]
    if str(launcher.parent) not in path_dirs:
        result.notes.append(f"{launcher.parent} is not in your PATH: add it to your shell profile to type 'erinix' anywhere.")
    return result


def uninstall_app(home: Path) -> list[Path]:
    home = Path(home)
    removed = []
    launcher = home / ".local" / "bin" / "erinix"
    for path, needs_marker in ((launcher, True), (home / ".local/share/applications/erinix.desktop", True),
                               (home / ".local/share/icons/hicolor/scalable/apps/erinix.svg", False),
                               (home / ".local/share/icons/hicolor/256x256/apps/erinix.png", False)):
        if os.path.islink(path) or not path.exists():
            continue
        if needs_marker and MARKER.encode() not in path.read_bytes()[:4096]:
            continue
        path.unlink()
        removed.append(path)
    return removed
